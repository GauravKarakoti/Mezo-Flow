import { network, artifacts } from "hardhat";
import * as dotenv from "dotenv";
import * as fs from "fs";
import * as path from "path";
import { fileURLToPath } from "url";

dotenv.config();

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

async function main() {
  const { ethers } = await network.connect();
  const [deployer] = await ethers.getSigners();
  console.log("Deploying with:", deployer.address);
  console.log(
    "Balance:",
    ethers.formatEther(await ethers.provider.getBalance(deployer.address))
  );

  const MUSD_ADDRESS = process.env.MUSD_ADDRESS!;
  const SAVINGS_VAULT_ADDRESS = process.env.SAVINGS_VAULT_ADDRESS!;
  const TREASURY_ADDRESS = process.env.TREASURY_ADDRESS || deployer.address;

  if (!MUSD_ADDRESS || !SAVINGS_VAULT_ADDRESS) {
    throw new Error("Set MUSD_ADDRESS and SAVINGS_VAULT_ADDRESS in .env");
  }

  console.log("\nDeploying MezoFlowVault with params:");
  console.log("  - MUSD:", MUSD_ADDRESS);
  console.log("  - Savings Vault:", SAVINGS_VAULT_ADDRESS);
  console.log("  - Treasury:", TREASURY_ADDRESS);

  const Vault = await ethers.getContractFactory("MezoFlowVault");
  const vault = (await Vault.deploy(
    MUSD_ADDRESS,
    SAVINGS_VAULT_ADDRESS,
    TREASURY_ADDRESS,
    "Mezo Flow MUSD",
    "mzFLOW-MUSD"
  )) as any;
  await vault.waitForDeployment();

  const vaultAddress = await vault.getAddress();
  console.log("MezoFlowVault deployed to:", vaultAddress);
  console.log("Asset (MUSD):", await vault.asset());
  console.log("Savings vault:", await vault.savingsVault());
  console.log("Treasury:", await vault.treasury());

  // --- Save Addresses & ABIs to Frontend ---
  const frontendSrcDir = path.resolve(__dirname, "../frontend/src");
  if (!fs.existsSync(frontendSrcDir)) {
    fs.mkdirSync(frontendSrcDir, { recursive: true });
  }

  const vaultArtifact = await artifacts.readArtifact("MezoFlowVault");

  const erc20Abi = [
    {
      type: "function",
      name: "allowance",
      stateMutability: "view",
      inputs: [
        { name: "owner", type: "address" },
        { name: "spender", type: "address" },
      ],
      outputs: [{ name: "", type: "uint256" }],
    },
    {
      type: "function",
      name: "approve",
      stateMutability: "nonpayable",
      inputs: [
        { name: "spender", type: "address" },
        { name: "value", type: "uint256" },
      ],
      outputs: [{ name: "", type: "bool" }],
    },
    {
      type: "function",
      name: "balanceOf",
      stateMutability: "view",
      inputs: [{ name: "account", type: "address" }],
      outputs: [{ name: "", type: "uint256" }],
    },
    {
      type: "function",
      name: "decimals",
      stateMutability: "view",
      inputs: [],
      outputs: [{ name: "", type: "uint8" }],
    },
    {
      type: "function",
      name: "symbol",
      stateMutability: "view",
      inputs: [],
      outputs: [{ name: "", type: "string" }],
    },
  ];

  const deploymentsPath = path.join(frontendSrcDir, "deployments.json");
  fs.writeFileSync(
    deploymentsPath,
    JSON.stringify(
      {
        chainId: 31611,
        vaultAddress,
        musdAddress: MUSD_ADDRESS,
        savingsVaultAddress: SAVINGS_VAULT_ADDRESS,
        treasuryAddress: TREASURY_ADDRESS,
        deployedAt: new Date().toISOString(),
      },
      null,
      2
    )
  );

  const abiFilePath = path.join(frontendSrcDir, "abi.ts");
  const abiFileContent = `// Auto-generated by scripts/deploy.ts — DO NOT EDIT MANUALLY
import type { Address } from "viem";

export const VAULT_ADDRESS: Address = "${vaultAddress}";

export const MUSD_ADDRESS: Address = "${MUSD_ADDRESS}";

export const SAVINGS_VAULT_ADDRESS: Address = "${SAVINGS_VAULT_ADDRESS}";

export const vaultAbi = ${JSON.stringify(vaultArtifact.abi, null, 2)} as const;

export const erc20Abi = ${JSON.stringify(erc20Abi, null, 2)} as const;
`;

  fs.writeFileSync(abiFilePath, abiFileContent, "utf-8");
  console.log(`\nSaved contract addresses and ABIs to:`);
  console.log(`  - ${abiFilePath}`);
  console.log(`  - ${deploymentsPath}`);

  console.log("\nVerification command:");
  console.log(
    `npx hardhat verify --network mezoTestnet ${vaultAddress} ${MUSD_ADDRESS} ${SAVINGS_VAULT_ADDRESS} ${TREASURY_ADDRESS} "Mezo Flow MUSD" "mzFLOW-MUSD"`
  );
}

main().catch((error) => {
  console.error(error);
  process.exitCode = 1;
});